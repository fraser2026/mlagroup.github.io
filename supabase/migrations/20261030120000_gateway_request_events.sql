-- Re-price a window after a list price is corrected or added.
CREATE OR REPLACE FUNCTION public.gateway_events_reprice(
  p_from timestamptz,
  p_to timestamptz,
  p_model text DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  n integer;
BEGIN
  UPDATE public.gateway_request_events
  SET cost_status = 'pending'
  WHERE created_at >= p_from
    AND created_at < p_to
    AND (p_model IS NULL OR model = p_model);
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END;
$$;

