-- Monthly partitions. Idempotent and lock-free when the partitions already
-- exist, so the gateway can call it on start-up to stay ahead of the calendar.
CREATE OR REPLACE FUNCTION public.gateway_events_ensure_partitions(p_months_ahead integer DEFAULT 3)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  month_start date := date_trunc('month', now() AT TIME ZONE 'utc')::date;
  last_month date := (date_trunc('month', now() AT TIME ZONE 'utc') + make_interval(months => greatest(0, least(p_months_ahead, 36))))::date;
  part_name text;
  created integer := 0;
BEGIN
  WHILE month_start <= last_month LOOP
    part_name := format('gateway_request_events_y%sm%s', to_char(month_start, 'YYYY'), to_char(month_start, 'MM'));
    IF to_regclass('public.' || part_name) IS NULL THEN
      EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.%I PARTITION OF public.gateway_request_events FOR VALUES FROM (%L) TO (%L)',
        part_name,
        (month_start::timestamp AT TIME ZONE 'utc'),
        ((month_start + interval '1 month')::timestamp AT TIME ZONE 'utc')
      );
      EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', part_name);
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated', part_name);
      EXECUTE format('GRANT ALL ON TABLE public.%I TO service_role', part_name);
      created := created + 1;
    END IF;
    month_start := (month_start + interval '1 month')::date;
  END LOOP;
  RETURN created;
END;
$$;

REVOKE ALL ON FUNCTION public.gateway_events_ensure_partitions(integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.gateway_events_ensure_partitions(integer) TO service_role;

