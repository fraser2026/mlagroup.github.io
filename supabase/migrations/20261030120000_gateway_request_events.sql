-- Gateway monitoring, phase 1.
-- Every governed request (allowed, blocked or failed) becomes one row in
-- gateway_request_events. Cost is priced in the database from the provider's
-- own usage block against dated list prices, so every figure can be traced to
-- the exact rates used and re-priced if a rate is corrected.

