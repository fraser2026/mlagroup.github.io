-- Amazon Bedrock list prices, imported from the AWS Price List bulk files.
--
-- Bedrock prices differ by region and by inference scope (in-region vs global cross-region), and
-- AWS publishes them per SKU with an effective date. Each price is a dated row: when AWS changes a
-- price, the open row is closed at the new effective date and a new row opens, so requests are
-- always priced at the rate that applied when they were made and history is never rewritten.
-- A price AWS stops listing is reported, not deleted. A model with no price is never guessed.

CREATE TABLE IF NOT EXISTS public.bedrock_prices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region text NOT NULL CHECK (region ~ '^[a-z]{2}(-[a-z]+)+-\d$'),
  provider text NOT NULL CHECK (provider ~ '^[a-z0-9][a-z0-9-]*$'),
  model_key text NOT NULL CHECK (model_key ~ '^[a-z0-9][a-z0-9-]*$'),
  model_name text NOT NULL,
  dimension text NOT NULL CHECK (dimension IN ('input', 'output', 'cache_read', 'cache_write_5m', 'cache_write_1h')),
  scope text NOT NULL CHECK (scope IN ('regional', 'global')),
  tier text NOT NULL CHECK (tier IN ('on_demand', 'batch')),
  long_context boolean NOT NULL DEFAULT false,
  currency text NOT NULL DEFAULT 'USD' CHECK (currency = 'USD'),
  usd_per_mtok numeric(14, 6) NOT NULL CHECK (usd_per_mtok >= 0),
  sku text NOT NULL,
  usage_type text NOT NULL,
  effective_from timestamptz NOT NULL,
  effective_to timestamptz,
  source_offer_version text NOT NULL,
  confirmed_offer_version text NOT NULL,
  source_url text NOT NULL,
  verified_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (effective_to IS NULL OR effective_to > effective_from),
  UNIQUE (region, provider, model_key, dimension, scope, tier, long_context, effective_from)
);

CREATE UNIQUE INDEX IF NOT EXISTS bedrock_prices_one_open
  ON public.bedrock_prices (region, provider, model_key, dimension, scope, tier, long_context)
  WHERE effective_to IS NULL;

CREATE INDEX IF NOT EXISTS bedrock_prices_lookup
  ON public.bedrock_prices (region, provider, model_key, scope, tier, effective_from DESC);

COMMENT ON TABLE public.bedrock_prices IS
  'Amazon Bedrock per-request list prices per region, model, token type and scope, per million tokens. '
  'Rows are dated; a price change closes the old row and opens a new one at the AWS effective date.';
COMMENT ON COLUMN public.bedrock_prices.scope IS
  'regional: in-region or geographic inference profile. global: global cross-region inference profile.';
COMMENT ON COLUMN public.bedrock_prices.confirmed_offer_version IS
  'Latest AWS price list version that still listed this price. Older than the region''s latest sync means AWS stopped listing it.';

ALTER TABLE public.bedrock_prices ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS bedrock_prices_select ON public.bedrock_prices;
CREATE POLICY bedrock_prices_select ON public.bedrock_prices
  FOR SELECT
  TO authenticated
  USING (true);

REVOKE ALL ON TABLE public.bedrock_prices FROM anon;
REVOKE INSERT, UPDATE, DELETE ON TABLE public.bedrock_prices FROM authenticated;
GRANT SELECT ON TABLE public.bedrock_prices TO authenticated;
GRANT ALL ON TABLE public.bedrock_prices TO service_role;

CREATE TABLE IF NOT EXISTS public.bedrock_price_sync_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region text NOT NULL,
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  status text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'completed', 'needs_review', 'failed')),
  offer_version text,
  published_at timestamptz,
  source_url text,
  added integer NOT NULL DEFAULT 0,
  changed integer NOT NULL DEFAULT 0,
  confirmed integer NOT NULL DEFAULT 0,
  no_longer_listed jsonb NOT NULL DEFAULT '[]'::jsonb,
  conflicts jsonb NOT NULL DEFAULT '[]'::jsonb,
  unrecognised jsonb NOT NULL DEFAULT '[]'::jsonb,
  left_unpriced jsonb NOT NULL DEFAULT '[]'::jsonb,
  error text
);

COMMENT ON COLUMN public.bedrock_price_sync_runs.left_unpriced IS
  'Models AWS lists with more than one price for the same key (retired context-size editions). Never priced.';

CREATE INDEX IF NOT EXISTS bedrock_price_sync_runs_region_started
  ON public.bedrock_price_sync_runs (region, started_at DESC);

COMMENT ON TABLE public.bedrock_price_sync_runs IS
  'One row per region per Bedrock price import. needs_review: AWS listed something the import would not apply on its own.';

ALTER TABLE public.bedrock_price_sync_runs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.bedrock_price_sync_runs FROM anon, authenticated;
GRANT ALL ON TABLE public.bedrock_price_sync_runs TO service_role;

-- Applies one parsed AWS price file for one region. Rows arrive as a JSON array from the
-- bedrock-price-sync edge function. Same price: confirmed. New key: added. Price changed with a
-- later effective date: old row closed, new row opened. Price changed without a later effective
-- date would mean rewriting history, so it is left as is and reported for review.
CREATE OR REPLACE FUNCTION public.bedrock_prices_apply(
  p_run_id bigint,
  p_region text,
  p_offer_version text,
  p_published_at timestamptz,
  p_source_url text,
  p_rows jsonb,
  p_unrecognised jsonb DEFAULT '[]'::jsonb,
  p_left_unpriced jsonb DEFAULT '[]'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  r record;
  cur public.bedrock_prices%ROWTYPE;
  v_added integer := 0;
  v_changed integer := 0;
  v_confirmed integer := 0;
  v_conflicts jsonb := '[]'::jsonb;
  v_missing jsonb;
  v_status text;
BEGIN
  IF jsonb_typeof(p_rows) <> 'array' OR jsonb_array_length(p_rows) = 0 THEN
    RAISE EXCEPTION 'No prices to apply for %', p_region;
  END IF;

  FOR r IN
    SELECT *
    FROM jsonb_to_recordset(p_rows) AS x(
      provider text, model_key text, model_name text, dimension text, scope text, tier text,
      long_context boolean, usd_per_mtok numeric, sku text, usage_type text, effective_from timestamptz
    )
    ORDER BY model_key, dimension, scope, tier, long_context
  LOOP
    SELECT * INTO cur
    FROM public.bedrock_prices p
    WHERE p.region = p_region AND p.provider = r.provider AND p.model_key = r.model_key
      AND p.dimension = r.dimension AND p.scope = r.scope AND p.tier = r.tier
      AND p.long_context = r.long_context AND p.effective_to IS NULL
    FOR UPDATE;

    IF NOT FOUND THEN
      INSERT INTO public.bedrock_prices (
        region, provider, model_key, model_name, dimension, scope, tier, long_context, usd_per_mtok,
        sku, usage_type, effective_from, source_offer_version, confirmed_offer_version, source_url
      ) VALUES (
        p_region, r.provider, r.model_key, r.model_name, r.dimension, r.scope, r.tier, r.long_context,
        r.usd_per_mtok, r.sku, r.usage_type, r.effective_from, p_offer_version, p_offer_version, p_source_url
      );
      v_added := v_added + 1;
    ELSIF cur.usd_per_mtok = r.usd_per_mtok THEN
      UPDATE public.bedrock_prices
      SET confirmed_offer_version = p_offer_version, verified_at = now(), model_name = r.model_name,
          sku = r.sku, usage_type = r.usage_type
      WHERE id = cur.id;
      v_confirmed := v_confirmed + 1;
    ELSIF r.effective_from > cur.effective_from THEN
      UPDATE public.bedrock_prices SET effective_to = r.effective_from WHERE id = cur.id;
      INSERT INTO public.bedrock_prices (
        region, provider, model_key, model_name, dimension, scope, tier, long_context, usd_per_mtok,
        sku, usage_type, effective_from, source_offer_version, confirmed_offer_version, source_url
      ) VALUES (
        p_region, r.provider, r.model_key, r.model_name, r.dimension, r.scope, r.tier, r.long_context,
        r.usd_per_mtok, r.sku, r.usage_type, r.effective_from, p_offer_version, p_offer_version, p_source_url
      );
      v_changed := v_changed + 1;
    ELSE
      v_conflicts := v_conflicts || jsonb_build_object(
        'model_key', r.model_key, 'dimension', r.dimension, 'scope', r.scope, 'tier', r.tier,
        'long_context', r.long_context, 'current_usd', cur.usd_per_mtok, 'current_from', cur.effective_from,
        'listed_usd', r.usd_per_mtok, 'listed_from', r.effective_from
      );
    END IF;
  END LOOP;

  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'model_key', p.model_key, 'dimension', p.dimension, 'scope', p.scope, 'tier', p.tier,
           'long_context', p.long_context, 'last_listed', p.confirmed_offer_version
         ) ORDER BY p.model_key, p.dimension, p.scope, p.tier, p.long_context), '[]'::jsonb)
  INTO v_missing
  FROM public.bedrock_prices p
  WHERE p.region = p_region AND p.effective_to IS NULL AND p.confirmed_offer_version <> p_offer_version;

  v_status := CASE
    WHEN jsonb_array_length(v_conflicts) > 0 OR jsonb_array_length(v_missing) > 0
      OR jsonb_array_length(coalesce(p_unrecognised, '[]'::jsonb)) > 0 THEN 'needs_review'
    ELSE 'completed'
  END;

  UPDATE public.bedrock_price_sync_runs
  SET finished_at = now(), status = v_status, offer_version = p_offer_version, published_at = p_published_at,
      source_url = p_source_url, added = v_added, changed = v_changed, confirmed = v_confirmed,
      no_longer_listed = v_missing, conflicts = v_conflicts, unrecognised = coalesce(p_unrecognised, '[]'::jsonb),
      left_unpriced = coalesce(p_left_unpriced, '[]'::jsonb)
  WHERE id = p_run_id;

  RETURN jsonb_build_object(
    'status', v_status, 'added', v_added, 'changed', v_changed, 'confirmed', v_confirmed,
    'no_longer_listed', jsonb_array_length(v_missing), 'conflicts', jsonb_array_length(v_conflicts),
    'unrecognised', jsonb_array_length(coalesce(p_unrecognised, '[]'::jsonb)),
    'left_unpriced', jsonb_array_length(coalesce(p_left_unpriced, '[]'::jsonb))
  );
END;
$$;

REVOKE ALL ON FUNCTION public.bedrock_prices_apply(bigint, text, text, timestamptz, text, jsonb, jsonb, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.bedrock_prices_apply(bigint, text, text, timestamptz, text, jsonb, jsonb, jsonb) TO service_role;

-- Price per million tokens for one Bedrock request, at the time it was made.
-- Returns no row when AWS has no price for that combination: callers mark the request unpriced.
CREATE OR REPLACE FUNCTION public.bedrock_price_at(
  p_region text,
  p_provider text,
  p_model_key text,
  p_scope text,
  p_tier text,
  p_long_context boolean,
  p_at timestamptz
)
RETURNS TABLE (dimension text, usd_per_mtok numeric, price_id bigint)
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  SELECT p.dimension, p.usd_per_mtok, p.id
  FROM public.bedrock_prices p
  WHERE p.region = p_region AND p.provider = p_provider AND p.model_key = p_model_key
    AND p.scope = p_scope AND p.tier = p_tier AND p.long_context = p_long_context
    AND p.effective_from <= p_at AND (p.effective_to IS NULL OR p.effective_to > p_at)
$$;

REVOKE ALL ON FUNCTION public.bedrock_price_at(text, text, text, text, text, boolean, timestamptz) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.bedrock_price_at(text, text, text, text, text, boolean, timestamptz) TO authenticated, service_role;

-- Scheduled cron authentication, same pattern as gateway reconciliation.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM vault.secrets WHERE name = 'bedrock_price_sync_cron') THEN
    PERFORM vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'bedrock_price_sync_cron',
      'Authenticates the scheduled bedrock-price-sync edge function run.'
    );
  END IF;
END
$$;

CREATE OR REPLACE FUNCTION public.bedrock_price_sync_cron_ok(p_secret text)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF p_secret IS NULL OR length(p_secret) < 32 THEN
    RETURN false;
  END IF;
  RETURN EXISTS (
    SELECT 1 FROM vault.decrypted_secrets s
    WHERE s.name = 'bedrock_price_sync_cron' AND s.decrypted_secret = p_secret
  );
END;
$$;

REVOKE ALL ON FUNCTION public.bedrock_price_sync_cron_ok(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.bedrock_price_sync_cron_ok(text) TO service_role;
